#!/usr/bin/env python3
"""Generate the Android TV banner and launcher icon (vector drawables) for Button Hooks.

The lettering is JetBrains Mono ExtraBold (SIL Open Font License) converted to outlines,
because vector drawables can't use fonts. Run from the repo root:

    python3 tools/make_banner.py [path/to/JetBrainsMono-ExtraBold.ttf]

Also writes SVG previews to build/banner-preview/.
"""
import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-ExtraBold.ttf"
BG, LINE, MID, TEXT, ACCENT = "#0E0E0E", "#3A3A3A", "#7A7A7A", "#E8E8E8", "#E0242F"

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm


def text_path(text, x, baseline, size, tracking=0.0):
    """Outline of `text` with its baseline at `baseline`, `size` px per em."""
    s = size / upm
    pen = SVGPathPen(glyphs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
    for ch in text:
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        x += glyphs[name].width * s + tracking
    return pen.getCommands(), x


def text_width(text, size, tracking=0.0):
    return sum(glyphs[cmap[ord(c)]].width for c in text) * size / upm + tracking * (len(text) - 1)


def hook_mark(ox, oy, k=1.0):
    """The mark: a red button sitting in the cup of a hard-edged hook. Returns [(color, path)]."""
    def r(x, y, w, h):
        return "M%g,%gh%gv%gh%gz" % (ox + x * k, oy + y * k, w * k, h * k, -w * k)
    return [
        (ACCENT, r(10, 26, 36, 36)),                                  # the button, caught in the cup
        (TEXT, r(50, 0, 6, 76) + r(0, 70, 56, 6) + r(0, 50, 6, 26)),  # stem, bend, barb
        (TEXT, r(44, -16, 18, 4) + r(44, -16, 4, 16)                  # square eye at the top
               + r(58, -16, 4, 16) + r(44, -4, 18, 4)),
    ]


def vector(w, h, layers, comment):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- %s -->" % comment,
           "<!-- Generated by tools/make_banner.py; edit that, not this. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="%ddp"' % w, '    android:height="%ddp"' % h,
           '    android:viewportWidth="%d"' % w, '    android:viewportHeight="%d">' % h]
    out += ['    <path android:fillColor="%s" android:pathData="%s" />' % (c, p) for c, p in layers]
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg(w, h, layers):
    body = "".join('<path fill="%s" d="%s"/>' % (c, p) for c, p in layers)
    return '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">%s</svg>' % (
        w * 3, h * 3, w, h, body)


# Banner, 320x180 (Android TV's launcher row).
W, H = 320, 180
banner = [
    (BG, "M0,0h%dv%dh-%dz" % (W, H, W)),
    (ACCENT, "M0,0h%dv5h-%dz" % (W, W)),                # hard red top edge
    (LINE, "M0,%dh%dv3h-%dz" % (H - 3, W, W)),          # grey bottom edge
]
banner += hook_mark(30, 54)

size, track = 46, -1.0
x0 = 118
line1, _ = text_path("BUTTON", x0, 86, size, track)
line2, _ = text_path("HOOKS", x0, 136, size, track)
banner += [(TEXT, line1), (ACCENT, line2)]
end = x0 + text_width("BUTTON", size, track)
banner.append((LINE, "M%g,95h%gv2h%gz" % (x0, end - x0, -(end - x0))))   # rule between the lines

# Launcher icon, 108x108: just the mark.
icon = [(BG, "M0,0h108v108h-108z"), (LINE, "M14,14h80v3h-80z M14,91h80v3h-80z")]
icon += hook_mark(32, 33, 0.72)

res = "app/src/main/res/drawable"
with open(os.path.join(res, "banner.xml"), "w") as f:
    f.write(vector(W, H, banner, "320x180 Android TV launcher banner: hook mark and BUTTON / HOOKS lettering."))
with open(os.path.join(res, "ic_launcher.xml"), "w") as f:
    f.write(vector(108, 108, icon, "Launcher icon: a red button caught in a hook."))
os.makedirs("build/banner-preview", exist_ok=True)
with open("build/banner-preview/banner.svg", "w") as f:
    f.write(svg(W, H, banner))
with open("build/banner-preview/icon.svg", "w") as f:
    f.write(svg(108, 108, icon))
print("text block ends at x=%.1f of %d" % (end, W))
